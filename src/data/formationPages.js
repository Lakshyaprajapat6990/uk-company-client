export function getFormationPage(slug) {
  return formationPages.find((page) => page.slug === slug)
}

export function getFormationSlugByTitle(title) {
  const aliases = {
    'Limited Companies (LTD)': 'ltd-or-private-limited-company-formation-in-uk',
    'Limited Companies for non UK residents': 'ltd-companies-for-non-uk-residents',
    'LLP Companies for non UK residents': 'llp-companies-for-non-uk-residents',
    'CIC-Limited by Guarantee Structure': 'community-interest-company-cic-lbg',
    'CIC- Limited by Shares Structure': 'community-interest-company-cic-ltd',
    'Formation with own Articles of Association': 'companies-with-owner-supplied-a-of-a',
  }

  if (aliases[title]) return aliases[title]

  const page = formationPages.find((p) => p.title === title)
  return page?.slug
}
